"""Turn a folder of photos into full-screen TV slides for the launcher.

    python tools/make_wallpapers.py "C:/path/to/photos"

Writes 1920x1080 JPGs to wallpapers/ plus wallpapers/list.js (both gitignored).
Every slide fills the whole screen:
  - wide photos fill it on their own
  - tall phone photos are placed three across
  - square / 4:3 photos are placed two across
so portraits stay whole instead of being cropped to a thin strip.
All metadata (EXIF, GPS) is dropped. Needs Pillow: pip install pillow
"""
import json
import sys
from pathlib import Path

from PIL import Image, ImageOps

W, H = 1920, 1080
GAP = 8
GAP_COLOR = (9, 9, 11)
EXTS = {".jpg", ".jpeg", ".png", ".webp"}
MAX_PHOTOS = 150


def fit(im, w, h):
    # People's faces sit in the upper part of most photos, so keep a bit more of the top.
    return ImageOps.fit(im, (w, h), Image.LANCZOS, centering=(0.5, 0.38))


def panels(images):
    n = len(images)
    slide = Image.new("RGB", (W, H), GAP_COLOR)
    width = (W - GAP * (n - 1)) // n
    x = 0
    for i, im in enumerate(images):
        w = W - x if i == n - 1 else width
        slide.paste(fit(im, w, H), (x, 0))
        x += w + GAP
    return slide


def build_slides(photos):
    wide, tall, mid = [], [], []
    for im in photos:
        ratio = im.width / im.height
        (wide if ratio >= 1.4 else tall if ratio < 0.62 else mid).append(im)

    slides = [fit(im, W, H) for im in wide]

    while len(tall) >= 3:
        slides.append(panels(tall[:3]))
        tall = tall[3:]
    mid += tall  # leftovers look fine two across
    while len(mid) >= 2:
        slides.append(panels(mid[:2]))
        mid = mid[2:]
    if mid:
        partner = photos[0] if photos[0] is not mid[0] else photos[-1]
        slides.append(panels([mid[0], partner]) if len(photos) > 1 else fit(mid[0], W, H))
    return slides


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    if not src.is_dir():
        sys.exit(f"Not a folder: {src}")

    out = Path(__file__).resolve().parent.parent / "wallpapers"
    out.mkdir(exist_ok=True)
    for old in out.glob("wall-*.jpg"):
        old.unlink()

    photos = []
    for path in sorted(p for p in src.iterdir() if p.is_file() and p.suffix.lower() in EXTS)[:MAX_PHOTOS]:
        try:
            photos.append(ImageOps.exif_transpose(Image.open(path)).convert("RGB"))
        except Exception as err:
            print(f"skip {path.name}: {err}")

    names = []
    for i, slide in enumerate(build_slides(photos), 1):
        name = f"wall-{i:02d}.jpg"
        slide.save(out / name, "JPEG", quality=86, optimize=True, progressive=True)
        names.append(name)

    (out / "list.js").write_text(
        "// Generated by tools/make_wallpapers.py\nwindow.LAUNCHER_WALLPAPERS = " + json.dumps(names) + ";\n",
        encoding="utf-8",
    )
    print(f"{len(photos)} photos -> {len(names)} full-screen slides in {out}")


if __name__ == "__main__":
    main()
